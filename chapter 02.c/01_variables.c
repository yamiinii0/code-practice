#include <stdio.h>

int main ()
{
    int a;              // Declaration of an integer variable 'a'
    a = 10; 
    int b = a;
    // %d is a format specifier for integers
    // %f is a format specifier for floating-point numbers
    // %c is a format specifier for characters
    printf("Value of b: %d\n", b);

    return 0;
}