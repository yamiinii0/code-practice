#include <stdio.h>
int main()
{
    printf("Hello, World!\n"); // New line
    printf("This is a tab:\t"); // Tab space
    printf("This is a backslash: \\\n"); // Backslash
    printf("This is a double quote: \"Hello\"\n"); // Double quote
    printf("This is a single quote: \'A\'\n"); // Single quote
    return 0;
}