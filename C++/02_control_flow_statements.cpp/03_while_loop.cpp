#include <iostream>
using namespace std;

int main()
{
    int i = 1; // initialization

    // while (condition)
    // {
    //     // code to be executed
    //     increment/decrement
    // }

    // print numbers from 1 to 10 using while loop
    while (i <= 10) // condition
    {
        cout << i << " ";
        i++; // increment
    }
    cout << endl;

    return 0;
}