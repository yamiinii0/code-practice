#include <iostream>
using namespace std;

int main ()
{
    // this is a comment 
    
    cout<< "Hello World!" << endl;
    cout<< "I like icecream! " <<endl;
    return 0;
}




// # --> preprocessor directive
// include --> is a preprocessor directive that tells the compiler to include the contents of a file in the program
// iostream --> is a header file that contains the declarations of the input/output stream objects such as cout and cin
// using namespace std --> is a directive that tells the compiler to use the standard namespace, which contains the definitions of the standard library functions and objects such as cout and cin
// main() --> is the entry point of the program, where the execution starts
// cout --> is an object of the ostream class that is used to output data to the console
// << --> is the insertion operator that is used to insert data into the output stream
// endl --> is a manipulator that is used to insert a newline character and flush the output buffer
// return 0 --> is used to indicate that the program has ended successfully