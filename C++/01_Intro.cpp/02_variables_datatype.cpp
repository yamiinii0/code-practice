#include <iostream>
using namespace std;

int main ()

{
    // int --->
    int age = 20;
    int year = 2026;
    int rate = 22.1;

    cout << rate << endl << year << endl << age << endl;

    // double (numbers including decimals)

    double price = 44.2;
    cout << price << endl;

    // single characters

    char grades = 'A';
    char initial = 'B';

    cout << grades << endl << initial << endl;

    // boolean (true or false)

    bool student = false;
    bool power = true;
    bool zip = true;

    cout << student << endl << zip << endl << power << endl;

    // string (objects that represents a sequence of text)

    string first_name = "Bhawesh";
    string last_name = "Verma";

    cout << first_name << endl << last_name << endl;
  
}